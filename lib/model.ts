// Token radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks protocols that record no token yet. A protocol is a board
// candidate when it records no token (no market cap, no CoinGecko id, no
// symbol) and is not a wrapped, staked or bridged product of a token that
// already trades: the same exclusion the snapshot's own watchlist uses
// (Bridge / Canonical Bridge / Liquid Staking / Liquid Restaking / Restaked
// BTC / CEX categories, a version marker at the end of the name, a whole word
// wrapped / staked / staking, or an exchange's name at the start). The
// watchlist is the floor: every one of its 40 slugs is on the board, and the
// early radar adds every other candidate below the watchlist floor.
//
// Implied value is derived from the snapshot's own figures only, never from
// a hand-kept list of names:
//
//   multiple   = the category's median mcap/TVL among live-token protocols
//                in the same category (at least 4 of them), else the global
//                median; winsorised to [0.05, 0.80] so a wrapped-asset
//                ratio from a bridge category cannot dominate the board
//   base       = tvl_usd x multiple
//   growthMult = 1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365)
//   implied    = max(1, round(base x growthMult x maturity))
//
// The market's own multiples are the anchor: a protocol's token, if it ever
// launches, is priced here the way the market prices the tokens of live
// protocols in the same line of business. The dashboard states the model and
// its multiples, and its sandbox recomputes the board from the same formula.

/** One protocol as the sealed snapshot carries it: exactly ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, stated on the dashboard and tunable in its sandbox. */
